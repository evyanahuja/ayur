import type { Metadata, Viewport } from "next";
import type { ReactNode } from "react";
import { Fraunces, Inter, Noto_Sans_Devanagari, Noto_Sans_Gujarati } from "next/font/google";
import "./globals.css";
import { SITE, SEO } from "@/content/site";
import { buildJsonLd } from "@/lib/jsonld";
import { SkipLink } from "@/components/SkipLink";

const fraunces = Fraunces({
  subsets: ["latin"],
  variable: "--font-display",
  display: "swap",
  weight: ["300", "400", "500", "600", "700"],
  style: ["normal", "italic"],
});

const inter = Inter({
  subsets: ["latin"],
  variable: "--font-sans",
  display: "swap",
  weight: ["400", "500", "600", "700"],
});

const notoDevanagari = Noto_Sans_Devanagari({
  subsets: ["devanagari", "latin"],
  variable: "--font-devanagari",
  display: "swap",
  weight: ["400", "500", "600", "700"],
});

const notoGujarati = Noto_Sans_Gujarati({
  subsets: ["gujarati", "latin"],
  variable: "--font-gujarati",
  display: "swap",
  weight: ["400", "500", "600", "700"],
});

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  themeColor: "#0e2b21",
};

export const metadata: Metadata = {
  metadataBase: new URL(SITE.siteUrl),
  title: { default: SEO.title, template: SEO.titleTemplate },
  description: SEO.description,
  applicationName: SITE.clinicName,
  authors: [{ name: SITE.doctorName, url: SITE.siteUrl }],
  creator: SITE.doctorName,
  category: "health",
  alternates: { canonical: "/" },
  formatDetection: { telephone: true, email: true, address: true },
  // Paste tokens into SEO.verification in src/content/site.ts (empty = skipped)
  verification: {
    ...(SEO.verification.google ? { google: SEO.verification.google } : {}),
    ...(SEO.verification.bing ? { other: { "msvalidate.01": SEO.verification.bing } } : {}),
  },
  openGraph: {
    type: "website",
    url: "/",
    siteName: SITE.clinicName,
    locale: SEO.locale,
    title: SEO.title,
    description: SEO.description,
    // image comes automatically from src/app/opengraph-image.tsx (1200x630)
  },
  twitter: {
    card: "summary_large_image",
    title: SEO.title,
    description: SEO.description,
  },
  robots: {
    index: true,
    follow: true,
    googleBot: {
      index: true,
      follow: true,
      "max-image-preview": "large",
      "max-snippet": -1,
      "max-video-preview": -1,
    },
  },
  // /icon, /apple-icon and /manifest.webmanifest are generated by
  // src/app/icon.tsx, src/app/apple-icon.tsx and src/app/manifest.ts
  icons: {
    icon: [
      { url: "/favicon.svg", type: "image/svg+xml" },
      { url: "/icon", type: "image/png", sizes: "512x512" },
    ],
    apple: [{ url: "/apple-icon", type: "image/png", sizes: "180x180" }],
  },
};

export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="en-IN" className={`${fraunces.variable} ${inter.variable} ${notoDevanagari.variable} ${notoGujarati.variable}`}>
      <body className="bg-[#fffdf8] text-slate-900 antialiased min-h-screen">
        <SkipLink />
        {children}
        <script
          type="application/ld+json"
          // escape "<" so no string in the data can close the script tag
          dangerouslySetInnerHTML={{ __html: JSON.stringify(buildJsonLd()).replace(/</g, "\\u003c") }}
        />
      </body>
    </html>
  );
}
